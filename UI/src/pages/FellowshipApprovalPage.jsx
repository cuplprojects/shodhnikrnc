function mapClaim(c) {
  return {
    id: c.id,
    fellowAppointmentId: c.fellowAppointmentId,
    workflowInstanceId: c.workflowInstanceId,
    scholarName: c.scholarName,
    rollNo: c.rollNo,
    department: c.departmentName,
    projectTitle: c.projectTitle,
    piName: c.piName,
    claimMonth: c.claimMonth,
    claimYear: c.claimYear,
    stipendAmount: c.fellowshipAmount,
    hraAmount: c.hraAmount,
    hraClaimed: c.hraClaimed,
    hraIsOverridden: c.hraIsOverridden,
    hraOverrideReason: c.hraOverrideReason,
    totalAmount: c.totalAmount,
    recommendedAmount: c.recommendedAmount,
    remarks: c.remarks,
    stage: c.currentStage,
    submittedAt: c.createdAt,
  };
}

