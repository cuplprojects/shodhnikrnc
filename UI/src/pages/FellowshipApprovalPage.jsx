function stageColor(stage) {
  switch (stage) {
    case STAGE.WITH_PI:
    case STAGE.RAISED:
      return "bg-blue-100 text-blue-800 dark:bg-blue-900/40 dark:text-blue-300";
    case STAGE.WITH_HOD:
      return "bg-violet-100 text-violet-800 dark:bg-violet-900/40 dark:text-violet-300";
    case STAGE.WITH_DA:
      return "bg-fuchsia-100 text-fuchsia-800 dark:bg-fuchsia-900/40 dark:text-fuchsia-300";
    case STAGE.WITH_SUPERINTENDENT:
      return "bg-purple-100 text-purple-800 dark:bg-purple-900/40 dark:text-purple-300";
    case STAGE.WITH_DR:
      return "bg-pink-100 text-pink-800 dark:bg-pink-900/40 dark:text-pink-300";
    case STAGE.WITH_DEAN:
      return "bg-indigo-100 text-indigo-800 dark:bg-indigo-900/40 dark:text-indigo-300";
    case STAGE.RETURNED_HOD:
    case STAGE.RETURNED_DA:
    case STAGE.RETURNED_SUPERINTENDENT:
    case STAGE.RETURNED_DR:
    case STAGE.RETURNED_DEAN:
      return "bg-amber-100 text-amber-800 dark:bg-amber-900/40 dark:text-amber-300";
    case STAGE.APPROVED:
      return "bg-emerald-100 text-emerald-800 dark:bg-emerald-900/40 dark:text-emerald-300";
    case STAGE.REJECTED:
      return "bg-red-100 text-red-800 dark:bg-red-900/40 dark:text-red-300";
    default:
      return "bg-slate-100 text-slate-700 dark:bg-slate-700 dark:text-slate-300";
  }
}

